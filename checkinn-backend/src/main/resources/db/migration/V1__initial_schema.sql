-- V1__initial_schema.sql
-- CheckInn baseline relational schema reproducing JPA entity definitions

-- 1. Users table
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255)
);

-- 2. Rooms table
CREATE TABLE IF NOT EXISTS rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_number VARCHAR(255),
    room_type VARCHAR(255),
    description VARCHAR(255),
    price_per_night NUMERIC(38, 2),
    capacity INTEGER,
    available BOOLEAN,
    bed_configuration VARCHAR(255)
);

-- 3. Room amenities collection table
CREATE TABLE IF NOT EXISTS room_amenities (
    room_id BIGINT NOT NULL,
    amenity VARCHAR(255) NOT NULL,
    amenity_order INTEGER NOT NULL,
    CONSTRAINT pk_room_amenities PRIMARY KEY (room_id, amenity_order),
    CONSTRAINT fk_room_amenities_room FOREIGN KEY (room_id) REFERENCES rooms(id) ON DELETE CASCADE
);

-- 4. Bookings table
CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_in_date DATE,
    check_out_date DATE,
    number_of_guests INTEGER,
    total_price NUMERIC(38, 2),
    status VARCHAR(255),
    user_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    CONSTRAINT fk_bookings_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_bookings_room FOREIGN KEY (room_id) REFERENCES rooms(id)
);

-- 5. Reviews table
CREATE TABLE IF NOT EXISTS reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rating INTEGER,
    comment VARCHAR(1000),
    created_at TIMESTAMP WITHOUT TIME ZONE,
    user_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    booking_id BIGINT NOT NULL,
    CONSTRAINT fk_reviews_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_reviews_room FOREIGN KEY (room_id) REFERENCES rooms(id),
    CONSTRAINT fk_reviews_booking FOREIGN KEY (booking_id) REFERENCES bookings(id)
);

-- 6. Email notifications table
CREATE TABLE IF NOT EXISTS email_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL UNIQUE,
    recipient_email VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    retry_count INTEGER NOT NULL DEFAULT 0,
    next_retry_at TIMESTAMP WITHOUT TIME ZONE,
    sent_at TIMESTAMP WITHOUT TIME ZONE,
    last_error VARCHAR(1000),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
